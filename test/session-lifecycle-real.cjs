/** Run with the installed DSH Electron runtime; uses no user profile or model calls. */
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { createRequire } = require('node:module')
const dshRequire = createRequire(path.join(process.env.DSH_TEST_APP, 'dsh/package.json'))
const { Context, Service } = dshRequire('@deepseek-ai/cordis')

async function main() {
  const { build } = require('esbuild')
  const out = path.resolve('.agent-tmp/trash-test/real-modules.cjs')
  await build({ stdin: { contents: `export { installSessionLifecycle } from './src/host/session-lifecycle.ts'; export { SessionTrash } from './src/host/session-trash.ts'; export { openTalkMapStore } from './src/host/store.ts'`, resolveDir: process.cwd() }, outfile: out, bundle: true, packages: 'external', platform: 'node', format: 'cjs' })
  const { installSessionLifecycle, SessionTrash, openTalkMapStore } = require(out)
  const home = await fs.mkdtemp(path.resolve('.agent-tmp/trash-test/real-home-'))
  const ctx = new Context()
  try {
    await fs.mkdir(path.join(home, 'sessions'))
    await ctx.plugin({ apply(c) {
      new Service(c, 'llm')
      new Service(c, 'tools')
      new class extends Service { constructor(c) { super(c, 'systemPrompt') } variable() {} }(c)
    } }).await()
    for (const pkg of ['dsh-session', 'dsh-session-projection', 'dsh-agent'])
      await ctx.plugin(dshRequire('@deepseek-ai/' + pkg).default).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-session-persistence-jsonl'), { root: path.join(home, 'sessions'), compression: 'zstd' }).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-session-query').default).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-agent-loop').default, { agents: [], maxParallelToolCalls: 1 }).await()
    // Match the real plugin's injected services, not plain-object table/cache doubles.
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-storage').default).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-storage-json'), {root:path.join(home, 'storages')}).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-storage-domain'), {backend:'json'}).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-session-projection-cache').default, {writeEveryEvents:1,writeIntervalMs:50}).await()
    await ctx.plugin(dshRequire('@deepseek-ai/dsh-workspace').default).await()
    let lifecycle
    const plugin = ctx.plugin({ inject: ['agents', 'sessions', 'agentLoop', 'sessionPersistence'], apply(c) { lifecycle = installSessionLifecycle(c) } })
    await plugin.await()
    await plugin.dispose()
    while (plugin.inertia) await plugin.inertia
    assert.ok(lifecycle)
    assert.equal(installSessionLifecycle(ctx), lifecycle, 'reload retains the same adapter and handles')
    const handle = await ctx.agents.create({ sessionId: 'session-real-idle', meta: { cwd: home } })
    assert.equal(ctx.agents.get(handle.agent.id), handle.agent)
    assert.equal(ctx.sessions.get(handle.agent.id), handle.agent.session)
    const header = handle.agent.session.header
    // Force materialization using a genuine native inbox event, without waking a model.
    handle.agent.inject({ id: 'msg-real', role: 'user', content: [{ type: 'text', text: 'keep this input' }], source: { kind: 'user' } })
    const child = await ctx.agents.create({sessionId:'session-real-child', parentAgent:handle.agent,
      meta:{cwd:home, origin:'subagent', parentSession:header.id, delegationDepth:1}})
    const grandchild = await ctx.agents.create({sessionId:'session-real-grandchild', parentAgent:child.agent,
      meta:{cwd:home, origin:'subagent', parentSession:child.agent.id, delegationDepth:2}})
    const fork = await ctx.agents.create({sessionId:'session-real-fork', meta:{cwd:home, parentSession:header.id}})
    for (const member of [child, grandchild, fork]) member.agent.inject({id:'msg-'+member.agent.id,role:'user',content:[{type:'text',text:'preserve lineage'}],source:{kind:'user'}})
    const workspace = await ctx.workspaceRegistry.create(home, 'Native lifecycle test')
    await workspace.attachSession(header.id)
    await workspace.attachSession(fork.agent.id)
    await ctx.workspaceRegistry.pinSession(header.id)
    await ctx.workspaceRegistry.archiveSession(fork.agent.id)
    await ctx.sessionProjectionCache.write(handle.agent.session)
    assert.ok(ctx.storageDomain.get('session_projcache').table('sessions').get(header.id))
    await ctx.sessionPersistence.flush()
    const originalHistory = await ctx.sessionQuery.readSession(header.id)
    assert.ok(JSON.stringify(originalHistory.events).includes('keep this input'))
    await assert.rejects(() => ctx.sessionPersistence.open(header.id, 'write'), { name: 'SessionAlreadyOwnedError' })
    await assert.rejects(() => ctx.sessionPersistence.acquireLease(header.id, undefined, path.dirname(ctx.sessionPersistence.locate(header).path)), { name: 'SessionAlreadyOwnedError' })
    const store = await openTalkMapStore(ctx.storageDomain)
    let trash
    const consumer = ctx.plugin({inject:['storageDomain','sessions','agents','sessionPersistence','sessionProjectionCache','workspaceRegistry'],
      apply(c) {trash = new SessionTrash(c, store, home)} })
    await consumer.await()
    await trash.initialize()
    const [deleted] = await trash.trash([header.id])
    assert.equal(deleted.status, 'trashed', JSON.stringify(deleted))
    assert.equal(ctx.agents.get(header.id), undefined)
    assert.equal(ctx.sessions.get(header.id), undefined)
    assert.deepEqual(new Set(deleted.affectedSessionIds), new Set([header.id, child.agent.id, grandchild.agent.id]))
    assert.equal(ctx.agents.get(child.agent.id), undefined)
    assert.equal(ctx.agents.get(grandchild.agent.id), undefined)
    assert.equal(ctx.agents.get(fork.agent.id), fork.agent, 'ordinary fork remains independent')
    assert.equal(workspace.sessionIds.includes(header.id), false)
    assert.equal(ctx.storageDomain.get('session_projcache').table('sessions').get(header.id), undefined)
    assert.equal((await ctx.sessionQuery.listSessions()).some(r => r.header.id === header.id), false)
    await assert.rejects(() => ctx.agents.resume({ resumeSessionId: header.id }), e => e.code === 'SESSION_TRASHED')
    assert.throws(() => handle.agent.inject({}), e => e.code === 'SESSION_TRASHED')
    const lease = await ctx.sessionPersistence.acquireLease(header.id, undefined, path.dirname(ctx.sessionPersistence.locate(header).path))
    await lease.release()
    const [restored] = await trash.restore([deleted.entryId])
    assert.equal(restored.status, 'restored', JSON.stringify(restored))
    assert.ok(workspace.sessionIds.includes(header.id))
    assert.ok(ctx.workspaceRegistry.pinnedSessionIds.includes(header.id))
    assert.ok(ctx.workspaceRegistry.archivedSessionIds.includes(fork.agent.id))
    assert.ok(ctx.storageDomain.get('session_projcache').table('sessions').get(header.id))
    const restoredRows = await ctx.sessionQuery.listSessions()
    for (const id of restored.affectedSessionIds) {
      const row = restoredRows.find(r => r.header.id === id)
      assert.ok(row, 'native session-list baseline includes every restored session')
      assert.equal(row.live, false, 'listing must not resume a restored Agent')
      assert.equal(row.persisted, true)
    }
    const history = await ctx.sessionQuery.readSession(header.id)
    assert.deepEqual(history.events.slice(0, originalHistory.events.length), originalHistory.events)
    const resumed = await ctx.agents.resume({ resumeSessionId: header.id })
    assert.equal(resumed.agent.id, header.id)
    let working = true
    const job = resumed.agent.runMaintenance(signal => new Promise(resolve => signal.addEventListener('abort', () => { working = false; resolve() }, { once: true })))
    const stopActivity = ctx.on('workspace/session-activity', async ({sessionId}, next) => sessionId === header.id && working ? [{kind:'job'}, ...await next()] : next())
    const stopProvider = ctx.on('workspace/session-stop', ({sessionId}) => {if(sessionId === header.id) resumed.agent.cancel({kind:'user'})})
    assert.equal((await trash.trash([header.id]))[0].error.code, 'SESSION_RUNNING')
    const [stopped] = await trash.trash([header.id], { stopActivity: true })
    assert.equal(stopped.status, 'trashed', JSON.stringify(stopped))
    await job
    stopActivity(); stopProvider()
    assert.equal((await trash.restore([stopped.entryId]))[0].status, 'restored')
    const owned = ctx.plugin({ inject: ['agents'], async apply(c) { await c.agents.resume({resumeSessionId: header.id}) } })
    await owned.await()
    assert.ok(ctx.agents.get(header.id))
    await owned.dispose()
    while (owned.inertia) await owned.inertia
    assert.equal(ctx.agents.get(header.id), undefined, 'native caller ownership is preserved')
    await fork.dispose()
    await consumer.dispose()
    await store.domain.close()
    console.log('PASS real rc.5 injected services + StorageDomain/ProjectionCache/WorkspaceRegistry/AgentLoop/SessionStore/JSONL-Zstd: idle delete, native disposal, Windows lease release, reload, caller ownership, recursive subagents/fork isolation, native stop, stale input/resume fences, restore/resume; no model calls')
  } finally {
    await ctx.fiber.dispose()
    while (ctx.fiber.inertia) await ctx.fiber.inertia
    assert.ok(home.startsWith(path.resolve('.agent-tmp/trash-test') + path.sep))
    await fs.rm(home, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
