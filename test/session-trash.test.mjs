test('startup rolls incomplete trash back, and incomplete restore returns to trash', async (t) => {
  const f = await fixture(t)
  const [r] = await f.trash.trash(['a'])
  const manifest = path.join(f.home, 'talk-map-trash', 'entries', r.entryId, 'manifest.json')
  let m = JSON.parse(await readFile(manifest, 'utf8'))
  m.state = 'restoring'
  m.operation = 'restore'
  const file = m.files[0],
    source = path.join(f.home, 'sessions', file.source),
    saved = path.join(path.dirname(manifest), 'logs', file.sessionId, file.name)
  await mkdir(path.dirname(source), { recursive: true })
  await writeFile(source, await readFile(saved))
  await rm(saved)
  await writeFile(manifest, JSON.stringify(m))
  const next = await f.restart()
  assert.equal(next.list()[0].state, 'trashed', JSON.stringify(next.list()))
  assert.equal(await has(source), false)
  m = JSON.parse(await readFile(manifest, 'utf8'))
  m.state = 'staging'
  m.operation = 'trash'
  await writeFile(manifest, JSON.stringify(m))
  const last = await f.restart()
  assert.equal(last.list().length, 0)
  assert.ok(await f.persistence.stat('a'))
  assert.ok(f.w.sessionIds.includes('a'))
})
