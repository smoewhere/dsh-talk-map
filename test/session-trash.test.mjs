const { SessionTrash } = await import(new URL(`file:///${output.replaceAll('\\', '/')}`))
const has = async (p) => {
  try {
    await access(p)
    return true
  } catch {
    return false
  }
}
class Table {
  rows = new Map()
  get(k) {
    return this.rows.get(k)
  }
  entries() {
    return this.rows.entries()
  }
  async put(k, v) {
    this.rows.set(k, structuredClone(v))
  }
  async delete(k) {
    return this.rows.delete(k)
  }
}
async function fixture(t) {
  const home = await mkdtemp(path.resolve('.agent-tmp/trash-test/home-'))
  assert.ok(home.startsWith(path.resolve('.agent-tmp/trash-test') + path.sep))
  t.after(() => rm(home, { recursive: true, force: true }))
  const workspace = path.join(home, 'project')
  await mkdir(workspace)
  await mkdir(path.join(home, 'sessions'))
  await writeFile(path.join(workspace, 'user.txt'), 'user data')
  await writeFile(path.join(workspace, 'generated.txt'), 'generated by session a')
  await mkdir(path.join(home, 'attachments'))
  await writeFile(path.join(home, 'attachments', 'shared.txt'), 'shared attachment')
  const headers = new Map(),
    locks = new Set(),
    live = new Set(),
    running = new Set(),
    events = []
  const cache = new Table()
  const state = {
    global: { version: 1, activeBoard: 'inbox', cameraByBoard: {}, layoutMemory: {} },
    archived: [],
    pinned: [],
  }
  const w = {
    id: 'workspace-a',
    path: workspace,
    title: 'Project',
    sessionIds: [],
    async attachSession(id) {
      if (!this.sessionIds.includes(id)) this.sessionIds.unshift(id)
    },
    async detachSession(id) {
      this.sessionIds = this.sessionIds.filter((s) => s !== id)
    },
    async insertSessionBefore(id, before) {
      this.sessionIds = this.sessionIds.filter((s) => s !== id)
      const at = this.sessionIds.indexOf(before)
      this.sessionIds.splice(at < 0 ? this.sessionIds.length : at, 0, id)
    },
  }
  const registry = {
    list: () => [w],
    get: (id) => (id === w.id ? w : undefined),
    create: async () => w,
    get archivedSessionIds() {
      return state.archived
    },
    get pinnedSessionIds() {
      return state.pinned
    },
    async archiveSession(id) {
      if (!state.archived.includes(id)) state.archived.push(id)
    },
    async unarchiveSession(id) {
      state.archived = state.archived.filter((s) => s !== id)
    },
    async pinSession(id) {
      state.pinned.unshift(id)
    },
    async unpinSession(id) {
      state.pinned = state.pinned.filter((s) => s !== id)
    },
  }
  const store = {
    cards: new Table(),
    edges: new Table(),
    digests: new Table(),
    global: () => state.global,
    setGlobal: async (v) => {
      state.global = v
    },
  }
  const persistence = {
    root: path.join(home, 'sessions'),
    locate: (h) => ({
      kind: 'jsonl',
      path: path.join(home, 'sessions', 'project', h.id, 'session.v4.jsonl'),
    }),
    async list() {
      const result = []
      for (const h of headers.values())
        if (await has(this.locate(h).path)) result.push({ header: h, formatStatus: 'current' })
      return result
    },
    async stat(id) {
      const h = headers.get(id)
      return h && (await has(this.locate(h).path)) ? { header: h } : undefined
    },
    async acquireLease(id, _cwd, dir) {
      if (locks.has(id)) {
        const e = new Error('locked')
        e.name = 'SessionAlreadyOwnedError'
        throw e
      }
      await mkdir(dir, { recursive: true })
      locks.add(id)
      return {
        release: async () => {
          locks.delete(id)
        },
      }
    },
    async open(id) {
      const lease = await this.acquireLease(
        id,
        undefined,
        path.dirname(this.locate(headers.get(id)).path),
      )
      return { close: () => lease.release() }
    },
  }
  const services = {
    sessionPersistence: persistence,
    storageDomain: {
      get: (name) => (name === 'session_projcache' ? { table: () => cache } : undefined),
    },
    sessionProjectionCache: { cachedSnapshot: (h) => cache.get(h.id)?.snapshot },
    sessions: { get: (id) => (live.has(id) ? {} : undefined) },
    agents: { get: (id) => (running.has(id) ? { status: 'running' } : undefined) },
    workspaceRegistry: registry,
    waterfall: async (_e, { sessionId }) => (running.has(sessionId) ? [{ kind: 'turn' }] : []),
    emit: (...args) => events.push(args),
  }
  async function add(id, extra = {}) {
    const h = { id, version: 4, createdAt: 1, isSeeded: false, cwd: workspace, ...extra }
    headers.set(id, h)
    const p = persistence.locate(h).path
    await mkdir(path.dirname(p), { recursive: true })
    await writeFile(p, JSON.stringify(h) + '\noriginal log ' + id)
    await cache.put(id, {
      snapshot: {
        asOfSeq: 1,
        values: { title: 'Title ' + id, sessionListMetadata: { blank: false, lastPromptAt: 2 } },
      },
    })
    w.sessionIds.push(id)
    await store.cards.put('card-' + id, {
      sessionId: id,
      boardId: 'inbox',
      x: 10,
      y: 20,
      createdAt: 1,
    })
    await store.digests.put(id, {
      summary: 'private ' + id,
      atSeq: 1,
      keyFindings: [],
      nextStep: '',
      generatedAt: 1,
    })
    state.global.layoutMemory[id] = { x: 10, y: 20 }
  }
  await add('a')
  await add('b')
  await add('child', { origin: 'subagent', parentSession: 'a' })
  await add('fork', { parentSession: 'a', isSeeded: true })
  await store.edges.put('edge', {
    fromCardId: 'card-a',
    toCardId: 'card-b',
    boardId: 'inbox',
    createdAt: 1,
    injection: { kind: 'link' },
  })
  state.archived = ['a']
  state.pinned = ['b']
  const trash = new SessionTrash(services, store, home)
  await trash.initialize()
  return {
    home,
    workspace,
    headers,
    locks,
    live,
    running,
    events,
    cache,
    state,
    w,
    store,
    persistence,
    services,
    trash,
    add,
    async restart() {
      const next = new SessionTrash(services, store, home)
      await next.initialize()
      return next
    },
  }
}

test('trash/restore owns only selected logs and metadata; workspace, fork and shared files survive', async (t) => {
  const f = await fixture(t),
    original = await readFile(f.persistence.locate(f.headers.get('a')).path)
  const [result] = await f.trash.trash(['a'])
  assert.equal(result.status, 'trashed', JSON.stringify(result))
  assert.deepEqual(result.affectedSessionIds, ['a', 'child'])
  assert.equal(await has(f.persistence.locate(f.headers.get('a')).path), false)
  assert.equal(await has(f.persistence.locate(f.headers.get('b')).path), true)
  assert.equal(await has(f.persistence.locate(f.headers.get('fork')).path), true)
  assert.equal(await readFile(path.join(f.workspace, 'user.txt'), 'utf8'), 'user data')
  assert.equal(
    await readFile(path.join(f.workspace, 'generated.txt'), 'utf8'),
    'generated by session a',
  )
  assert.equal(
    await readFile(path.join(f.home, 'attachments', 'shared.txt'), 'utf8'),
    'shared attachment',
  )
  assert.equal(f.w.sessionIds.includes('a'), false)
  assert.equal(f.store.cards.get('card-a'), undefined)
  assert.equal(f.cache.get('a'), undefined)
  assert.equal(f.store.edges.get('edge'), undefined)
  assert.equal(f.state.global.layoutMemory.a, undefined)
  assert.ok(f.events.some((e) => e[0] === 'api-session/removed' && e[1] === 'a'))
  const next = await f.restart()
  assert.equal(next.list().length, 1)
  const [restored] = await next.restore([result.entryId])
  assert.equal(restored.status, 'restored')
  assert.deepEqual(await readFile(f.persistence.locate(f.headers.get('a')).path), original)
  assert.deepEqual(f.w.sessionIds, ['a', 'b', 'child', 'fork'])
  assert.deepEqual(f.state.archived, ['a'])
  assert.ok(f.store.cards.get('card-a'))
  assert.ok(f.store.edges.get('edge'))
  assert.ok(f.cache.get('a'))
  assert.equal((await f.restart()).list().length, 0)
})
test('partial batch failure; running child rejects whole tree; in-use and stopped-but-retained reject', async (t) => {
  const f = await fixture(t)
  f.running.add('a')
  assert.equal((await f.trash.trash(['a']))[0].error.code, 'SESSION_RUNNING')
  f.running.clear()
  f.running.add('child')
  const results = await f.trash.trash(['a', 'b'])
  assert.equal(results[0].error.code, 'SESSION_RUNNING')
  assert.equal(results[1].status, 'trashed')
  assert.ok(f.store.cards.get('card-a'))
  assert.ok(f.store.cards.get('card-child'))
  assert.equal(f.store.cards.get('card-b'), undefined)
  f.running.clear()
  f.live.add('a')
  assert.equal((await f.trash.trash(['a']))[0].error.code, 'SESSION_RELEASE_UNAVAILABLE')
  f.live.clear()
  assert.equal((await f.trash.trash(['a']))[0].status, 'trashed')
})
