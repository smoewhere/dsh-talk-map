/**
 * 从 app.asar 抽出 DSH 真实主题 CSS（静态色板 + 明暗色别名），写成 test/dsh-theme.css。
 * harness / demo 页引它，而不是手写 stub —— 背景与质感从此和宿主同源。
 *   node scripts/extract-theme.mjs
 */
import fs from 'node:fs'
import path from 'node:path'

const ASAR = process.env.DSH_TEST_ASAR ?? path.join(process.env.LOCALAPPDATA ?? '', 'Programs', 'DeepSeek Harness', 'resources', 'app.asar')
const OUT = 'test/dsh-theme.css'
const text = fs.readFileSync(ASAR).toString('latin1')

/** 选择器后第一个 `{…}` 块；同名多块时取最长的（= 完整别名集）。 */
function largestBlock(selector) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const re = new RegExp(escaped + '\\{([^}]*)\\}', 'g')
  let best = ''
  for (const match of text.matchAll(re)) {
    if (match[1].length > best.length) best = match[1]
  }
  return best
}

// 静态色板：body{--dsw-static-…} 里最长的一块
let statics = ''
for (const match of text.matchAll(/body\{(--dsw-static-[^}]+)\}/g)) {
  if (match[1].length > statics.length) statics = match[1]
}

let light = ''
for (const match of text.matchAll(/body\s*\{\s*(--dsw-alias-[^}]+)\}/g)) {
  if (match[1].length > light.length) light = match[1]
}
const dark = largestBlock('body[data-ds-dark-theme]')
if (statics.length < 500 || light.length < 500 || dark.length < 500) {
  console.error('extraction too small:', { statics: statics.length, light: light.length, dark: dark.length })
  process.exit(1)
}

const css = [
  '/* Generated by scripts/extract-theme.mjs from the installed DSH app.asar.',
  '   Do not edit by hand — re-run the script after a DSH upgrade. */',
  `body{${statics}}`,
  `body{${light}}`,
  `body[data-ds-dark-theme]{${dark}}`,
  '',
].join('\n')
fs.writeFileSync(OUT, css, 'utf8')
console.log(`${OUT}: statics ${statics.length}B + light ${light.length}B + dark ${dark.length}B`)
